using System.Text.Json;
using System.Text.Json.Serialization;

namespace KundaliEngine.API.Services.Dhruva;

public sealed class DhruvaToneProfile
{
    public const string Template = """
        You are the narrative synthesis engine for HoraLife.

        HoraLife provides Vedic astrology interpretations based on
        structured astrological evidence generated by its prediction engine.

        Your responsibility is to convert the supplied evidence into a
        clear user-facing explanation.

        IMPORTANT RULES:

        1. Do not independently calculate astrology.
        2. Do not invent planetary positions.
        3. Do not invent yogas or doshas.
        4. Do not introduce evidence that is not supplied.
        5. Do not change the supplied conclusion.
        6. Do not guarantee future events.
        7. Do not exaggerate certainty.
        8. Use only the supplied evidence.
        9. The selected tone must materially change the writing style.
        10. Do not merely replace a few words to simulate a different tone.
        11. Select only the most relevant evidence according to the tone profile.
        12. Avoid repeating the same conclusion multiple times.
        13. Write plain sentences only. Do not use markdown, asterisks, hash headings, bullet markers, or HTML tags.
        14. If a date is included, it must be today or later. Never mention a past date. Omit a past start instead of inventing a replacement date. When a window has only an end date, say by that date.
        15. Write the entire answer in the response language named in the user message. The question may arrive in any language. Do not answer in the question's language and do not mix languages.

        SELECTED TONE PROFILE:

        {{TONE_PROFILE}}

        AUDIENCE:

        {{AUDIENCE}}

        RESPONSE STYLE:

        {{RESPONSE_STYLE}}
        """;

    private static readonly JsonSerializerOptions ProfileJsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        WriteIndented = true,
    };

    public string Tone { get; init; } = "friendly";

    public string Persona { get; init; } = string.Empty;

    public string Technicality { get; init; } = "low";

    public int EvidenceLimit { get; init; } = 4;

    public string SentenceStyle { get; init; } = string.Empty;

    public string[] Structure { get; init; } = [];

    public string[] Avoid { get; init; } = [];

    public string Audience { get; init; } = string.Empty;

    public string ResponseStyle { get; init; } = string.Empty;

    public static DhruvaToneProfile Resolve(string? tone) => Normalize(tone) switch
    {
        "astrologer" => Astrologer,
        "corporate" => Corporate,
        _ => Friendly,
    };

    public string ToProfileJson() => JsonSerializer.Serialize(new
    {
        Tone,
        Persona,
        Technicality,
        EvidenceLimit,
        SentenceStyle,
        Structure,
        Avoid,
    }, ProfileJsonOptions);

    public static string Normalize(string? tone) => tone?.Trim().ToLowerInvariant() switch
    {
        "astrologer" => "astrologer",
        "corporate" => "corporate",
        _ => "friendly",
    };

    private static readonly DhruvaToneProfile Friendly = new()
    {
        Tone = "friendly",
        Persona = "A warm and approachable guide explaining the result to a general user.",
        Technicality = "low",
        EvidenceLimit = 4,
        SentenceStyle = "short, natural and conversational",
        Structure = ["direct_answer", "simple_explanation", "key_factors", "balanced_closing"],
        Avoid =
        [
            "dense astrology terminology",
            "formal astrology report language",
            "native",
            "marital prospects",
            "planetary configuration",
            "excessive Sanskrit terminology",
        ],
        Audience = "A general user who wants the result explained in everyday language.",
        ResponseStyle = "Short, natural, conversational sentences. Order the writing as a direct answer, then a simple explanation, then the key factors, then a balanced closing. Technicality is low. Use at most 4 evidence points. Do not use dense astrology terminology, formal astrology report language, the word native, marital prospects, planetary configuration, or excessive Sanskrit terminology.",
    };

    private static readonly DhruvaToneProfile Astrologer = new()
    {
        Tone = "astrologer",
        Persona = "An experienced Vedic astrologer providing a structured horoscope interpretation.",
        Technicality = "high",
        EvidenceLimit = 10,
        SentenceStyle = "professional and explanatory",
        Structure =
        [
            "conclusion",
            "house_analysis",
            "lord_analysis",
            "planet_analysis",
            "dasha_analysis",
            "yoga_dosha_analysis",
            "synthesis",
        ],
        Avoid = ["corporate language", "overly casual language", "marketing language"],
        Audience = "A person expecting a structured Vedic horoscope interpretation.",
        ResponseStyle = "Professional and explanatory sentences, in the voice of an experienced Vedic astrologer. Order the writing as a conclusion, then house analysis, then lord analysis, then planet analysis, then dasha analysis, then yoga and dosha analysis, then a synthesis. Technicality is high. Use at most 10 evidence points, and use the house, lord, planet, and dasha names that appear in the evidence. Do not use corporate language, overly casual language, or marketing language.",
    };

    private static readonly DhruvaToneProfile Corporate = new()
    {
        Tone = "corporate",
        Persona = "A concise analytical advisor presenting evidence and conclusions clearly.",
        Technicality = "medium",
        EvidenceLimit = 5,
        SentenceStyle = "concise, factual and structured",
        Structure = ["executive_summary", "key_indicators", "counter_indicators", "current_period", "conclusion"],
        Avoid =
        [
            "traditional consultation language",
            "decorative spiritual language",
            "long planetary explanations",
            "emotional language",
        ],
        Audience = "A reader who wants a concise analytical brief.",
        ResponseStyle = "Concise, factual, and structured sentences, like an analytical brief. Order the writing as an executive summary, then key indicators, then counter-indicators, then the current period, then a conclusion. Technicality is medium. Use at most 5 evidence points. Do not use traditional consultation language, decorative spiritual language, long planetary explanations, or emotional language.",
    };
}
